import { CODEX_SEGMENT_MAX } from './labels'

// A segment suggested from a title, so a person types the name once. Cyrillic is transliterated
// (the common passport scheme, simplified), everything else outside a-z/0-9 becomes a hyphen. Only
// a suggestion: the field stays editable, and a segment the person typed is never overwritten.
const CYRILLIC: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f',
  х: 'h', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

export function segmentFromTitle(title: string): string {
  return title
    .toLowerCase()
    .split('')
    .map((char) => CYRILLIC[char] ?? char)
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, CODEX_SEGMENT_MAX)
}
