// Чем правятся поля задачи.
//
// Состав возможностей редактора — решение о том, что поле ПРИНИМАЕТ, а это знание доменное:
// общий компонент не обязан знать, что у цели задачи не бывает заголовков. Поэтому наборы
// объявлены здесь, а `components/markdown/editor/modes.ts` держит только родовые `full` и
// `simple`.
//
// **Ручки перетаскивания нет ни в одном поле, и это вынужденно.** Ручку расширение ставит левее
// блока, ей нужно 36px колонки — а поле лежит внутри карточки с заголовком секции, и колонка
// сдвинула бы текст относительно этого заголовка. Вынести ручку в отступ карточки тоже нельзя:
// его 16px на неё не хватает. Блоки в полях задачи переставляются вырезанием, а не перетаскиванием.
import type { Feature } from '@/components/markdown/editor/modes'

/**
 * Постановка и план — всё, что умеет редактор, кроме ручки.
 *
 * Сюда пишут прозу с разбором: подразделы, списки, листинги, сравнительные таблицы, ссылки на
 * соседние сущности. Ограничивать тут нечего — ровно этот набор рендерер и показывает.
 */
export const TASK_DOCUMENT_FEATURES: readonly Feature[] = [
  'heading', 'list', 'quote', 'codeBlock', 'divider', 'table',
  'bold', 'italic', 'strike', 'code', 'link', 'entityRef',
  'slash',
]

/**
 * Границы и критерии — перечни, а не документы.
 *
 * Заголовка внутри поля на полтора абзаца быть не может: он делил бы на разделы то, что и так
 * один раздел. Таблицы и линии там же не к месту. Список остаётся — критерии почти всегда список.
 */
export const TASK_BRIEF_FEATURES: readonly Feature[] = [
  'list',
  'bold', 'italic', 'strike', 'code', 'link', 'entityRef',
  'slash',
]
