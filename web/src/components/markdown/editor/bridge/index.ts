//
//   1. второй проход равен первому (стабильность);
//   2. текст не меняется — не добавляется экранирование, которого не требовал парсер;
//   3. непереносимое объявлено (`UNSUPPORTED`), а не умалчивается.
//
// Все три проверяет панель кругового прохода на странице дизайн-системы.
