"""DTO модуля ``workspace`` — контракты обеих поверхностей: web-вьюера и агента.

**Префикс ``Agent`` = поверхность агента.** Класс с этим префиксом возвращается тулами MCP
(``mcp/``) и больше никем, всё остальное — контракты web-вьюера. Граница сплошная: общих
контрактов у поверхностей нет даже там, где наборы полей совпадают — ``WorkspaceListRow`` и
``AgentWorkspaceRow`` описывают одну строку таблицы и намеренно разошлись. Человеку нужны
оформление и ключи подписей счётчиков, агенту — числа; сведи их в один класс, и поле,
добавленное ради колонки, начнёт стоить агенту контекста в каждой сессии.

Докстринга у агентского класса нет намеренно: pydantic кладёт его в JSON-схему тула описанием, и
агент оплачивает его при каждом подключении. Поэтому пояснения агентских контрактов живут в
комментариях НАД классом.

Код в выдаче несёт презентационный префикс (``WORKSPACE@…``) — за это отвечает ``prefixed``
из ``workspace.codes``: сериализатор надевает тип-слово только в JSON, внутренний
``model_dump()`` остаётся голым. На вход код принимается в обеих формах — снимает префикс
``bare_code`` на границе ручки, а не здесь: DTO описывает ответ, разбор адреса — работа маршрута.

Даты отдаются ядровым ``DatetimeUTCStr`` (SQL-формат без ``T``) — ровно его ждёт фронт-парсер
``web/src/shared/utils/date.ts`` (Luxon ``fromSQL``).

Содержимого пространства в ответе нет и быть не может: модуль не знает, что в нём лежит. Вместо
него едут **счётчики**, объявленные модулями поверх (``stats.py``), — пара «ключ + сколько» плюс
ключ подписи, по которому текст находит интерфейс.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict

from src.core.utils.date import DatetimeUTCStr
from src.modules.workspace.codes import prefixed
from src.modules.workspace.constants import WORKSPACE_CODE_PREFIX

# Презентационный тип кода: голый хеш внутрь, ``WORKSPACE@<hash>`` наружу.
WorkspaceCode = prefixed(WORKSPACE_CODE_PREFIX)


class WorkspaceRow(BaseModel):
    """Пространство целиком: тела у него нет, поэтому скан и деталь — один набор полей.

    ``deleted_at`` едет наружу намеренно: список умеет показывать удалённое (``include_deleted``),
    и отличить живую карточку от удалённой клиент должен по данным, а не по тому, из какого
    запроса она приехала.
    """

    model_config = ConfigDict(from_attributes=True)

    code: WorkspaceCode
    title: str
    description: str = ""
    color: str = ""
    icon: str = ""
    created_at: DatetimeUTCStr
    updated_at: DatetimeUTCStr
    deleted_at: DatetimeUTCStr | None = None


class WorkspaceCounterRow(BaseModel):
    """Один счётчик содержимого: чей он, как его подписать и сколько насчиталось.

    Подпись — ключ сообщения, а не текст: русский текст в модуле, который про язык ничего не
    знает, был бы вторым местом правки при каждом переименовании.
    """

    key: str
    label_key: str
    count: int


class WorkspaceListRow(WorkspaceRow):
    """Строка списка: карточка плюс счётчики того, что в ней держат модули поверх.

    Счётчики считают только живое: удалённая строка для остального кода не существует, и
    показать её в «внутри 3 зоны» значило бы обещать человеку то, чего он внутри не найдёт.
    Эти же числа читает диалог удаления — потому счётчики и живут в строке списка, а не
    достаются отдельным запросом на каждое открытие окна.

    Набор счётчиков — не фиксированный контракт: он зависит от того, какие модули подняты. Пустой
    список — законный ответ (никто ничего не объявил), и интерфейс рисует карточку без чисел.
    """

    counters: list[WorkspaceCounterRow] = []


# Пространство, в котором выполнен вызов, — едет в КАЖДОМ ответе связанного инструмента. Не
# служебное поле и не отладка: у агента нет другого способа заметить, что он работает не в том
# контуре, — список чужих задач выглядит как список задач, а пустой как «работы нет». Названное
# пространство превращает эту ошибку из невидимой в очевидную с первого ответа, и стоит это
# двух полей.
class AgentScope(BaseModel):
    workspace: WorkspaceCode
    workspace_title: str


# Пространство глазами агента: чем называется, что внутри и работает ли он в нём.
# Счётчики отданы плоским словарём (``{"groups": 2, "tasks": 12}``), а не списком строк с
# ключами подписей, как в интерфейсе: ключ подписи нужен тому, кто рисует по-русски, а агенту
# нужно число рядом с именем. Набор ключей зависит от состава приложения — это тот же реестр
# (``stats.py``), и фиксированным контрактом он не является.
class AgentWorkspaceRow(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    code: WorkspaceCode
    title: str
    description: str = ""
    counters: dict[str, int] = {}
    active: bool = False


# Ответ привязки: то же пространство плюс то, чего агент про свой выбор не знает, — надолго ли
# он и чем делается постоянным.
class AgentWorkspaceBound(AgentWorkspaceRow):
    note: str


__all__ = [
    "AgentScope",
    "AgentWorkspaceBound",
    "AgentWorkspaceRow",
    "WorkspaceCode",
    "WorkspaceCounterRow",
    "WorkspaceListRow",
    "WorkspaceRow",
]
