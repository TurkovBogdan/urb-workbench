"""Мягкая граница длины текстовых полей модуля.

Размер поля — **не** ошибка валидации: слишком длинное название не повод отказать в записи.
Поэтому усечение, а не исключение, и делается оно в CRUD — на входе в хранилище.

Режем по **code points**: ``value[:limit]`` на ``str`` считает символы Unicode, а не байты, так
что кириллица не рубится посреди символа. Это совпадает с символьной семантикой ``VARCHAR(n)``
в PostgreSQL; на SQLite ширина не проверяется вовсе — там усечение и есть единственная граница.
"""

from __future__ import annotations


def clip(value: str | None, limit: int) -> str:
    """Усечь строку до ``limit`` символов Unicode; ``None`` → ``""`` (колонка не nullable)."""
    return (value or "")[:limit]


__all__ = ["clip"]
