"""Константы модуля ``workspace`` — длина кода, префикс и размеры полей карточки.

Единый источник для трёх мест, которые обязаны совпадать: ORM-модель (``String(n)``), миграция
и усечение в CRUD (``text.clip``). Разъехались бы они — расхождение всплыло бы только на
PostgreSQL: SQLite ширину ``VARCHAR`` не проверяет вовсе.

``CODE_LEN`` — договор НЕ только этого модуля: на пространство ссылаются коды-чужаки из модулей
поверх него (``tasks_group.workspace_code`` и его соседи), и ширина их колонки взята отсюда.
Менять длину — значит менять её во всех ссылающихся таблицах одной миграцией.
"""

from __future__ import annotations

# ── presentation code prefix (граница, НЕ хранилище — см. workspace.codes) ──
# В базе лежит голый hex-код; тип-слово надевается на выходе и снимается на входе.
WORKSPACE_CODE_PREFIX = "WORKSPACE"

# Длина кода в hex-символах. Та же, что у сущностей модулей поверх: код пространства едет в их
# таблицы, и разная ширина колонок под один и тот же код — это будущая усечённая ссылка.
CODE_LEN = 10

# ── размеры текстовых колонок ──
TITLE_MAX = 96
DESCRIPTION_MAX = 512
COLOR_MAX = 32
ICON_MAX = 64


__all__ = [
    "CODE_LEN",
    "COLOR_MAX",
    "DESCRIPTION_MAX",
    "ICON_MAX",
    "TITLE_MAX",
    "WORKSPACE_CODE_PREFIX",
]
